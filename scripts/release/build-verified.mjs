// Builds supabase/release/<migration>_verified.sql: the migration, unchanged, wrapped so it proves
// it left every existing row alone — and cancels itself if it didn't.
//
//   node scripts/release/build-verified.mjs
//
// The wrapper, in ONE transaction (repeatable read, so other brokers' writes during these seconds
// don't count as changes):
//   1. fingerprints every row of every existing table in public, plus storage.objects (which files
//      exist) and auth.users (who can sign in) — a count and a hash per table;
//   2. runs the migration exactly as written;
//   3. fingerprints the same tables again, ignoring only the columns the migration adds;
//   4. if any table differs, raises an error: the whole transaction is rolled back and nothing
//      from the migration is applied;
//   5. otherwise commits and shows a summary (accounts, documents, requests, follow-ups, …).
//
// Works in the Supabase SQL editor (paste the file, Run) and with psql -f. Creates nothing
// permanent beyond what the migration itself creates (the fingerprints live in a temp table).
import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('../../', import.meta.url).pathname;

/** Per migration: the columns it adds to existing tables (left out of the comparison), extra checks, tables to lock first. */
export const RELEASES = {
  '0047_requests_sent_quota_agencies': {
    addedColumns: { document_requests: ['delivery_status', 'sent_at'] },
    lock: ['public.document_requests'],
    // Existing requests must come out as "unconfirmed" — never "sent" — with no sent time.
    assertions: [
      [`select count(*) = 0 from public.document_requests where delivery_status <> 'unconfirmed' or sent_at is not null`, 'Existing requests were not all marked unconfirmed.'],
    ],
  },
  '0048_upload_limits_and_verification': {
    addedColumns: {},
    lock: ['storage.buckets'],
    assertions: [
      [`select coalesce((select value::text = 'false' from public.app_settings where key = 'require_upload_verification'), false)`, 'Upload enforcement must start switched off.'],
    ],
  },
};

const fingerprint = (phase, addedColumns) => `
do $fp$
declare
  t record;
  drop_keys jsonb := '${JSON.stringify(addedColumns)}'::jsonb;
begin
  for t in
    select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind in ('r', 'p')
       and ('${phase}' = 'before' or exists (select 1 from pg_temp._release_check b where b.phase = 'before' and b.tbl = c.relname))
     order by 1
  loop
    execute format(
      'insert into pg_temp._release_check select %L, %L, count(*), md5(coalesce(string_agg(x, E''\\n'' order by x), '''')) from (select (to_jsonb(r) - %L::text[])::text as x from public.%I r) s',
      '${phase}', t.relname, coalesce((select array_agg(v) from jsonb_array_elements_text(drop_keys -> t.relname) v), '{}'::text[]), t.relname);
  end loop;
  insert into pg_temp._release_check
    select '${phase}', 'storage.objects', count(*), md5(coalesce(string_agg(bucket_id || '/' || name || '#' || coalesce(metadata ->> 'size', ''), E'\\n' order by bucket_id, name), '')) from storage.objects;
  insert into pg_temp._release_check
    select '${phase}', 'auth.users', count(*), md5(coalesce(string_agg(id::text || ' ' || coalesce(email, ''), E'\\n' order by id), '')) from auth.users;
end
$fp$;`;

export function buildVerified(name) {
  const cfg = RELEASES[name];
  const migration = readFileSync(`${ROOT}supabase/migrations/${name}.sql`, 'utf8').trimEnd();
  const tag = name.slice(0, 4);
  return `-- ${tag} — VERIFIED APPLY (generated by scripts/release/build-verified.mjs; do not edit by hand).
--
-- Applies supabase/migrations/${name}.sql exactly as written, inside one transaction that
-- first fingerprints all existing data (every row of every table in public, plus which files are
-- in storage and which users exist) and checks it again afterwards. If anything existing changed —
-- other than the new column(s) this migration adds — it stops with an error and NOTHING is applied.
-- On success the last result shows what was checked.
--
-- Run it in the Supabase SQL editor (paste the whole file, Run) or: psql "$DATABASE_URL" -f this-file

begin isolation level repeatable read;
set local lock_timeout = '10s';     -- don't queue behind a long query; just fail and retry later
set local statement_timeout = '5min';
${cfg.lock.map((t) => `lock table ${t} in share row exclusive mode;  -- writes wait a few seconds; reads continue`).join('\n')}

create temp table if not exists _release_check (phase text not null, tbl text not null, n bigint not null, h text not null, primary key (phase, tbl)) on commit preserve rows;
truncate pg_temp._release_check;
${fingerprint('before', {})}

-- ===================== migration ${name} (verbatim) =====================
${migration}
-- ===================== end of migration =====================

${fingerprint('after', cfg.addedColumns)}

do $check$
declare
  changed text;
begin
  select string_agg(b.tbl || ' (' || b.n || ' → ' || coalesce(a.n::text, 'missing') || ' rows)', ', ' order by b.tbl) into changed
    from pg_temp._release_check b
    left join pg_temp._release_check a on a.phase = 'after' and a.tbl = b.tbl
   where b.phase = 'before' and (a.tbl is null or a.n <> b.n or a.h <> b.h);
  if changed is not null then
    raise exception 'STOPPED — existing data would change in: %. Nothing from ${tag} was applied.', changed;
  end if;
${cfg.assertions.map(([q, msg]) => `  if not (${q}) then raise exception 'STOPPED — %. Nothing from ${tag} was applied.', ${`'${msg.replace(/'/g, "''")}'`}; end if;`).join('\n')}
end
$check$;

commit;

-- What was checked (all unchanged):
select '${tag} applied and verified' as result,
       (select n from pg_temp._release_check where phase = 'before' and tbl = 'submissions') as accounts,
       (select n from pg_temp._release_check where phase = 'before' and tbl = 'documents') as documents,
       (select n from pg_temp._release_check where phase = 'before' and tbl = 'document_requests') as client_requests,
       (select coalesce(sum(case when jsonb_typeof(missing_items) = 'array' then jsonb_array_length(missing_items) end), 0) from public.submissions) as checklist_items,
       (select coalesce(sum(case when jsonb_typeof(follow_ups) = 'array' then jsonb_array_length(follow_ups) end), 0) from public.submissions) as account_follow_ups,
       (select count(*) from public.document_requests where next_follow_up is not null) as request_follow_ups,
       (select n from pg_temp._release_check where phase = 'before' and tbl = 'activity_events') as activity_entries,
       (select n from pg_temp._release_check where phase = 'before' and tbl = 'storage.objects') as stored_files,
       (select count(*) from pg_temp._release_check where phase = 'before') as tables_checked;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const name of Object.keys(RELEASES)) {
    const out = `${ROOT}supabase/release/${name.slice(0, 4)}_verified.sql`;
    writeFileSync(out, buildVerified(name));
    console.log('wrote', out.replace(ROOT, ''));
  }
}
